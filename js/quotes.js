// Topics offered as one-click chips in settings, in display order.
export const TOPICS = ['computer-science', 'mathematics', 'science', 'philosophy', 'stoicism',
  'existentialism', 'abstract', 'design', 'art', 'literature', 'technology'];

const TAG = /(?:^|\s)#[\w-]+/g;

// Custom quotes: "text — author #tag #tag" (tags optional).
function parseExtra(text) {
  return (text || '').split('\n')
    .map((l) => l.trim()).filter((l) => l && !l.startsWith('#'))
    .map((l) => {
      const tags = (l.match(TAG) || []).map((t) => t.trim().slice(1).toLowerCase()).join(' ');
      l = l.replace(TAG, '').trim();
      const m = l.match(/^(.*?)\s+[—–-]{1,2}\s+([^—–-]+)$/);
      return m ? [m[1], m[2], tags] : [l, 'unknown', tags];
    });
}

// Every quote the settings allow, as [text, author, tags]. Topics match tags;
// keywords match tags, text or author. Untagged custom quotes always show.
export function pickable(q) {
  const extra = parseExtra(q.extra);
  const all = [...(q.builtin ? QUOTES : []), ...extra];
  const topics = q.topics || [];
  const words = (q.keywords || '').toLowerCase().split(/[,\s]+/).map((w) => w.replace(/^#/, '')).filter(Boolean);
  if (!topics.length && !words.length) return all;
  return all.filter((quote) => {
    const [text, author, tags] = quote;
    if (!tags && extra.includes(quote)) return true;
    const t = tags.split(' ');
    if (topics.some((x) => t.includes(x))) return true;
    const hay = `${text} ${author} ${tags}`.toLowerCase();
    return words.some((w) => hay.includes(w));
  });
}
